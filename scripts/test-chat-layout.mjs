// Run against the Vite dev server. All HTTP auth and WebSocket RPCs are mocked;
// this script never starts real agents or writes to a real project.
// PLAYWRIGHT_MODULE may name an isolated installation's absolute index.mjs.
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const artifacts = await mkdtemp(join(tmpdir(), 'octiq-chat-test-'));
const base = process.env.OCTIQ_TEST_URL || 'http://127.0.0.1:5273/';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:process.env.OCTIQ_TEST_BROWSER || 'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1600,height:1000}, reducedMotion:'reduce'});
const projects = [{id:'pa',name:'Project Alpha',primary_path:'/test/alpha'},{id:'pb',name:'Project Beta',primary_path:'/test/beta'}];
const chats = [{id:'a',projectId:'pa',title:'Alpha chat'},{id:'b',projectId:'pb',title:'Beta chat'},{id:'c',projectId:'pa',title:'Another chat'}].map(c=>({...c,modelId:'claude-sonnet',sessionId:null,access:null,createdAt:1,updatedAt:2,pinned:false}));
const calls=[]; const errors=[];
await context.route('**/token',r=>r.fulfill({body:'mock-token'}));
await context.route('**/auth',r=>r.fulfill({body:'ok'}));
await context.routeWebSocket(/.*/, ws=>ws.onMessage(raw=>{
 const data=JSON.parse(String(raw)); if(data.t!=='invoke') return;
 calls.push(data);
 let result=[];
 if(data.cmd==='list_workspaces') result=projects;
 if(data.cmd==='chat_index_list') result=chats;
 if(data.cmd==='chat_page') result={events:[],context:[],before:null};
 if(data.cmd==='chat_queue_state') result={live:false,queuedTurnIds:[]};
 if(data.cmd==='git_status') result={branch:'main',files:[]};
 ws.send(JSON.stringify({t:'reply',id:data.id,ok:true,result}));
 if(data.cmd==='chat_interrupt') ws.send(JSON.stringify({t:'event',event:'chat-status',payload:{key:data.args.key,kind:'exit',text:'',code:0}}));
}));
const page=await context.newPage(); page.setDefaultTimeout(30000); page.on('pageerror',e=>errors.push(String(e)));
await page.goto(base + '#/p/project-alpha/c/a');
await page.locator('textarea').waitFor();
assert.equal(page.frames().length, 1);
assert.equal(await page.getByRole('button', {name: /Open.*beside|Return to split/}).count(), 0);
await page.locator('textarea').fill('alpha draft');
await page.locator('.chat-title').filter({hasText:'Another chat'}).click();
await page.waitForFunction(()=>location.hash.endsWith('/c/c'));
await page.goBack();
await page.waitForFunction(()=>location.hash.endsWith('/c/a'));
assert.equal(await page.locator('textarea').inputValue(),'alpha draft');
await page.goForward();
await page.waitForFunction(()=>location.hash.endsWith('/c/c'));
// Old split bookmarks and stored layout preferences cannot bring split mode back.
await page.evaluate(()=>{
 localStorage.setItem('octiq.v2.lastSplit', '#/split?left=a&right=b&focus=right');
 localStorage.setItem('octiq.v2.splitWidth', '35');
});
await page.goto(base + '?pane=1&side=right#/split?left=a&right=b&focus=right');
await page.locator('textarea').waitFor();
await page.waitForFunction(()=>location.hash.endsWith('/c/b'));
assert.equal(new URL(page.url()).search, '');
assert.equal(page.frames().length, 1);
await page.reload();
await page.locator('textarea').waitFor();
await page.waitForFunction(()=>location.hash.endsWith('/c/b'));
// Sending and stopping still target the selected chat and its project.
await page.locator('textarea').fill('mock beta');
await page.locator('textarea').press('Enter');
await page.getByRole('button',{name:'Stop',exact:true}).waitFor();
const starts=calls.filter(c=>c.cmd==='chat_start');
assert(starts.some(c=>c.args.key==='chat:b'&&c.args.cwd==='/test/beta'));
await page.getByRole('button',{name:'Stop',exact:true}).click();
await page.waitForFunction(()=>!document.querySelector('button[title="Stop"]'));
assert.deepEqual(calls.filter(c=>c.cmd==='chat_interrupt').map(c=>c.args.key),['chat:b']);
await page.screenshot({path:join(artifacts,'single-chat.png')});
const missing = await context.newPage();
await missing.goto(base + '#/split?left=a&right=missing&focus=right');
await missing.getByRole('heading',{name:'Chat unavailable'}).waitFor();
assert(missing.url().includes('missing'));
assert.equal(await missing.locator('textarea').count(),0);
await missing.close();
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Chat actions',exact:true}).click();
assert.equal(await page.getByRole('button', {name: /Open.*beside|Return to split/}).count(), 0);
assert.equal(page.frames().length, 1);
await page.screenshot({path:join(artifacts,'mobile.png')});
assert.deepEqual(errors,[]);
console.log(JSON.stringify({ok:true,artifacts,starts:starts.map(c=>({key:c.args.key,cwd:c.args.cwd})),errors},null,2));
await browser.close();
